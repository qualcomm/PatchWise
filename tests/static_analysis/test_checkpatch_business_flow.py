from unittest.mock import Mock

import pytest
from git import Actor, Repo

from patchwise import main
from patchwise.mail_handler import handler
from patchwise.patch_review.static_analysis.checkpatch import Checkpatch
from patchwise.patch_review.static_analysis.checkpatch_filter import filter_report

FIXTURES = Path(__file__).parent / "fixtures"
TITLE_MESSAGE = (
    "probe: Add SoM support\n\nSupport a System on Module board.\n\n"
    "Signed-off-by: Probe Author <probe@example.invalid>"
)
BODY_MESSAGE = (
    "probe: Add board support\n\nSupport a SoM (System on Module) board.\n\n"
    "Signed-off-by: Probe Author <probe@example.invalid>"
)
ERROR = (
    "drivers/probe.c:3: ERROR:TRAILING_WHITESPACE: trailing whitespace\n"
    "+int probe_value; $\n\n"
)


def complete(messages, validate):
    data = json.loads(messages[1]["content"])
    value = {
        "decisions": [
            {
                "id": finding["id"],
                "suppress": "TYPO_SPELLING" in finding["text"],
                "reason": "SoM is expanded in the reviewed commit",
            }
            for finding in data["findings"]
        ]
    }
    return value if validate(value) else None


@pytest.mark.parametrize(
    "fixture,message",
    [
        ("checkpatch-commit-title.txt", TITLE_MESSAGE),
        ("checkpatch-commit-body.txt", BODY_MESSAGE),
    ],
)
def test_real_commit_spelling_context_reaches_filter(tmp_path, fixture, message):
    raw = (FIXTURES / fixture).read_text()
    completion = Mock(side_effect=complete)

    assert (
        filter_report(raw, message, "+/* board support */", completion, tmp_path) == ""
    )
    completion.assert_called_once()
    payload = json.loads(completion.call_args.args[0][1]["content"])
    assert payload["findings"][0]["text"] == raw[: raw.index("total:")]


@pytest.mark.parametrize(
    "replacement,message",
    [
        ("fatal: an unrelated tool failed", TITLE_MESSAGE),
        ("Subject: [PATCH] unrelated subject", TITLE_MESSAGE),
        ("An unrelated commit body", BODY_MESSAGE),
    ],
)
def test_unknown_commit_context_does_not_allow_suppression(
    tmp_path, replacement, message
):
    raw = (FIXTURES / "checkpatch-commit-title.txt").read_text()
    raw = raw.replace("Subject: [PATCH] probe: Add SoM support", replacement)
    completion = Mock(side_effect=AssertionError("unsupported input must abstain"))

    assert filter_report(raw, message, "diff", completion, tmp_path) == raw
    completion.assert_not_called()


def mixed_report():
    title = (FIXTURES / "checkpatch-commit-title.txt").read_text()
    return (
        title[: title.index("total:")]
        + ERROR
        + ("total: 1 errors, 1 warnings, 0 checks, 3 lines checked\n")
    )


def test_commit_context_cannot_be_attached_to_a_code_location(tmp_path):
    raw = (FIXTURES / "checkpatch-commit-title.txt").read_text()
    raw = raw.replace(":0: WARNING:", "drivers/probe.c:1: WARNING:")
    completion = Mock(side_effect=AssertionError("invalid code context must abstain"))

    assert filter_report(raw, TITLE_MESSAGE, "diff", completion, tmp_path) == raw
    completion.assert_not_called()


@pytest.mark.parametrize("fix", [False, True], ids=["review", "review-and-fix"])
def test_empty_rerun_removes_only_the_selected_current_report(
    tmp_path, monkeypatch, fix
):
    repo = Repo.init(tmp_path / "repo")
    actor = Actor("Test Author", "test@example.invalid")
    source = Path(repo.working_tree_dir) / "board.c"
    source.write_text("/* board */\n")
    repo.index.add(["board.c"])
    commit = repo.index.commit("Add board", author=actor, committer=actor)
    args = argparse.Namespace(
        repo_path=repo.working_tree_dir,
        commit_dir="",
        commits=[commit.hexsha],
        additional_context="",
        fix=fix,
        output_dir=str(tmp_path / "output"),
    )
    review = object.__new__(Checkpatch)
    review.docker_manager = SimpleNamespace(container_name="unused-test-container")
    monkeypatch.setattr(
        main, "get_selected_reviews_from_args", lambda _: {"Checkpatch"}
    )
    raw = (FIXTURES / "checkpatch-commit-title.txt").read_text()
    run_review = Mock(
        side_effect=[
            SimpleNamespace(results={review: raw}),
            SimpleNamespace(results={review: ""}),
            SimpleNamespace(results={review: ""}),
        ]
    )
    monkeypatch.setattr(main, "review_commit", run_review)
    if fix:
        monkeypatch.setattr(
            main,
            "fix_reported_issues",
            Mock(
                side_effect=[
                    {"CheckpatchFix": "a previous generated patch"},
                    {"CheckpatchFix": ""},
                    {"CheckpatchFix": ""},
                ]
            ),
        )

    main.run_local_mode(args)
    output_dir = Path(args.output_dir) / commit.hexsha
    current = output_dir / "checkpatch.txt"
    assert current.read_text() == raw
    other_check = output_dir / "sparse.txt"
    other_check.write_text("retained other check")
    other_commit = Path(args.output_dir) / "other-commit/checkpatch.txt"
    other_commit.parent.mkdir()
    other_commit.write_text("retained other commit")
    other_fix = output_dir / "sparsefix.patch"
    other_fix.write_text("retained unselected fixer")
    if fix:
        assert (
            output_dir / "checkpatchfix.patch"
        ).read_text() == "a previous generated patch"

    main.run_local_mode(args)
    main.run_local_mode(args)  # Missing old output must also be safe.

    assert not current.exists()
    assert other_check.read_text() == "retained other check"
    assert other_commit.read_text() == "retained other commit"
    assert other_fix.read_text() == "retained unselected fixer"
    assert not (output_dir / "checkpatchfix.patch").exists()


@pytest.mark.parametrize("mixed", [False, True], ids=["all-suppressed", "mixed"])
def test_filtered_results_control_mail_reply(tmp_path, monkeypatch, mixed):
    raw = (
        mixed_report()
        if mixed
        else (FIXTURES / "checkpatch-commit-title.txt").read_text()
    )
    output = filter_report(raw, TITLE_MESSAGE, "diff", complete, tmp_path)
    expected = ERROR + "total: 1 errors, 0 warnings, 0 checks, 3 lines checked\n"
    assert output == (expected if mixed else "")
    review = object.__new__(Checkpatch)
    review.docker_manager = SimpleNamespace(container_name="unused-test-container")
    message = EmailMessage()
    message["From"] = "Probe Author <probe@example.invalid>"
    message["Subject"] = "[PATCH] Add board support"
    message["Message-Id"] = "<offline-test@example.invalid>"
    message.set_content("Offline test message")
    client = Mock()
    client.search.return_value = [1]
    client.fetch_message.return_value = message
    monkeypatch.setattr(handler, "should_ignore", lambda *_: False)
    monkeypatch.setattr(handler, "is_plain_text", lambda *_: True)
    monkeypatch.setattr(handler, "find_deprecated_list", lambda *_: None)
    monkeypatch.setattr(handler, "get_patch_series", lambda *_: ([], None, None))
    monkeypatch.setattr(handler, "format_series_context", lambda *_: "")
    monkeypatch.setattr(
        handler,
        "test_patch_from_mail",
        lambda *_: SimpleNamespace(commit="abc123", results={review: output}),
    )

    handler.process_mail(
        client, [], {"Checkpatch"}, SimpleNamespace(deprecated_lists={}), fix=False
    )

    assert client.send_response.call_count == int(mixed)
    if mixed:
        reply = client.send_response.call_args.args[1]
        assert ERROR in reply
        assert "TYPO_SPELLING" not in reply
    client.mark_as_processed.assert_called_once_with(1)
